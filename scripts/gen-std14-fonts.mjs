// Regenerate src/std14data.ts from the vendored fonts in fonts/.
// Usage: node scripts/gen-std14-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontsDir = join(root, 'fonts');
const outFile = join(root, 'src', 'std14data.ts');

// TrueType source file -> Standard-14 face key (StdFont).
const MAP = {
  'LiberationSans-Regular.ttf': 'Helvetica',
  'LiberationSans-Bold.ttf': 'Helvetica-Bold',
  'LiberationSans-Italic.ttf': 'Helvetica-Oblique',
  'LiberationSans-BoldItalic.ttf': 'Helvetica-BoldOblique',
  'LiberationSerif-Regular.ttf': 'Times-Roman',
  'LiberationSerif-Bold.ttf': 'Times-Bold',
  'LiberationSerif-Italic.ttf': 'Times-Italic',
  'LiberationSerif-BoldItalic.ttf': 'Times-BoldItalic',
  'LiberationMono-Regular.ttf': 'Courier',
  'LiberationMono-Bold.ttf': 'Courier-Bold',
  'LiberationMono-Italic.ttf': 'Courier-Oblique',
  'LiberationMono-BoldItalic.ttf': 'Courier-BoldOblique',
  'StandardSymbolsPS.ttf': 'Symbol',
  'D050000L.ttf': 'ZapfDingbats',
};

let body = '';
for (const [file, face] of Object.entries(MAP)) {
  const raw = readFileSync(join(fontsDir, file));
  const b64 = deflateSync(raw, { level: 9 }).toString('base64');
  body += `  ${JSON.stringify(face)}: ${JSON.stringify(b64)},\n`;
}

const out = `// GENERATED by scripts/gen-std14-fonts.mjs - DO NOT EDIT BY HAND.
// Deflate-compressed, base64 TrueType data for the 14 Standard-14 substitute
// faces (Liberation + URW). Regenerate: node scripts/gen-std14-fonts.mjs
import type { StdFont } from './metrics.js';

export const STD14_DATA: Record<StdFont, string> = {
${body}};
`;
writeFileSync(outFile, out);
console.log('wrote', outFile, '(' + (out.length / 1048576).toFixed(2) + ' MB)');
