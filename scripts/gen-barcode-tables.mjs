// Generates src/pdf417data.ts and src/datamatrixdata.ts from ZXing's own
// sources at a pinned tag, and writes ZXing's PDF417 error-correction
// coefficients to test/fixtures/barcode-zxing/pdf417-ec.json for the suite to
// check our computed generator polynomials against.
//
// The tables are data, not code: a hand-typed copy of 2,787 bar patterns is
// exactly the kind of transcription this repository refuses to ship. Run with
// `npm run gen:barcodes`; it needs network access and is not run by `npm test`.
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';

const TAG = 'zxing-3.5.3';
const BASE = `https://raw.githubusercontent.com/zxing/zxing/${TAG}/core/src/main/java/com/google/zxing`;
const FILES = {
  pdf417: 'pdf417/encoder/PDF417.java',
  hle: 'pdf417/encoder/PDF417HighLevelEncoder.java',
  pec: 'pdf417/encoder/PDF417ErrorCorrection.java',
  sym: 'datamatrix/encoder/SymbolInfo.java',
  sym144: 'datamatrix/encoder/DataMatrixSymbolInfo144.java',
};

async function fetchText(path) {
  const res = await fetch(`${BASE}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.text();
}

const src = {};
const sha = {};
for (const [k, p] of Object.entries(FILES)) {
  src[k] = await fetchText(p);
  sha[k] = createHash('sha256').update(src[k]).digest('hex');
}

/** The body of `NAME = { ... };` with nested braces, as a string. */
function braceBlock(text, name) {
  const at = text.indexOf(`${name} = {`);
  if (at < 0) throw new Error(`${name} not found`);
  let i = text.indexOf('{', at);
  let depth = 0;
  for (let j = i; j < text.length; j++) {
    if (text[j] === '{') depth++;
    else if (text[j] === '}' && --depth === 0) return text.slice(i, j + 1);
  }
  throw new Error(`${name}: unbalanced`);
}

/** `{{a, b}, {c}}` as number[][] (hex or decimal literals). */
function nested(block) {
  const inner = block.slice(1, -1);
  const rows = [];
  const re = /\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(inner))) rows.push(m[1].split(',').map((s) => s.trim()).filter(Boolean).map(Number));
  return rows;
}

/** `{a, b, c}` as number[]. */
function flat(block) {
  return block.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean).map(Number);
}

function constant(text, name) {
  const m = new RegExp(`${name} = (0x[0-9a-fA-F]+|\\d+);`).exec(text);
  if (!m) throw new Error(`${name} not found`);
  return Number(m[1]);
}

// --- PDF417 -----------------------------------------------------------------
const table = nested(braceBlock(src.pdf417, 'CODEWORD_TABLE'));
if (table.length !== 3 || table.some((r) => r.length !== 929))
  throw new Error(`CODEWORD_TABLE shape ${table.map((r) => r.length)}`);
const start = constant(src.pdf417, 'START_PATTERN');
const stop = constant(src.pdf417, 'STOP_PATTERN');
const mixed = flat(braceBlock(src.hle, 'TEXT_MIXED_RAW'));
const punct = flat(braceBlock(src.hle, 'TEXT_PUNCTUATION_RAW'));
if (mixed.length !== 30 || punct.length !== 30) throw new Error('text tables are not 30 long');
const ec = nested(braceBlock(src.pec, 'EC_COEFFICIENTS'));
if (ec.length !== 9 || ec.some((r, l) => r.length !== 1 << (l + 1)))
  throw new Error(`EC_COEFFICIENTS shape ${ec.map((r) => r.length)}`);

const hex = (n) => `0x${n.toString(16)}`;
const rowsOf = (arr, per) => {
  const out = [];
  for (let i = 0; i < arr.length; i += per) out.push(`  ${arr.slice(i, i + per).join(', ')},`);
  return out.join('\n');
};
const header = (what) => `// GENERATED by scripts/gen-barcode-tables.mjs (npm run gen:barcodes) -- do not edit.
// ${what}, extracted from ZXing ${TAG}:
${Object.entries(FILES).map(([k, p]) => `//   ${p}  sha256 ${sha[k]}`).join('\n')}
`;

writeFileSync('src/pdf417data.ts', `${header('PDF417 bar patterns and text-compaction tables')}
/** Start pattern, 17 modules, MSB first (1 = bar). */
export const PDF417_START = ${hex(start)};
/** Stop pattern, 18 modules, MSB first. */
export const PDF417_STOP = ${hex(stop)};

/** Bar patterns for codewords 0..928 in clusters 0, 3 and 6 (row % 3), each
 *  17 modules MSB first with 1 = bar. */
export const PDF417_PATTERNS: readonly (readonly number[])[] = [
${table.map((r) => `[\n${rowsOf(r.map(hex), 8)}\n]`).join(',\n')},
];

/** Text compaction, mixed sub-mode: the character code of value v, 0 where v
 *  is a control (latch or shift) rather than a character. */
export const PDF417_TEXT_MIXED: readonly number[] = [${mixed.join(', ')}];
/** Text compaction, punctuation sub-mode, as PDF417_TEXT_MIXED. */
export const PDF417_TEXT_PUNCT: readonly number[] = [${punct.join(', ')}];
`);

mkdirSync('test/fixtures/barcode-zxing', { recursive: true });
writeFileSync('test/fixtures/barcode-zxing/pdf417-ec.json',
  JSON.stringify({ source: `${TAG} ${FILES.pec}`, sha256: sha.pec, coefficients: ec }) + '\n');

// --- Data Matrix --------------------------------------------------------------
const symBlock = braceBlock(src.sym, 'PROD_SYMBOLS');
const rows = [];
const re = /new SymbolInfo\(([^)]*)\)|new DataMatrixSymbolInfo144\(\)/g;
let m;
while ((m = re.exec(symBlock))) {
  if (!m[1]) {
    const s = /super\(([^)]*)\)/.exec(src.sym144);
    const blocks = /getInterleavedBlockCount\(\)\s*\{\s*return (\d+);/.exec(src.sym144);
    if (!s || !blocks) throw new Error('DataMatrixSymbolInfo144 not understood');
    const a = s[1].split(',').map((x) => x.trim());
    // super(rect, data, ec, regionW, regionH, regions, rsBlockData, rsBlockError)
    rows.push({ rect: a[0] === 'true', data: +a[1], ec: +a[2], regionW: +a[3], regionH: +a[4],
      regions: +a[5], blocks: +blocks[1] });
    continue;
  }
  const a = m[1].split(',').map((x) => x.trim());
  const r = { rect: a[0] === 'true', data: +a[1], ec: +a[2], regionW: +a[3], regionH: +a[4], regions: +a[5] };
  // An explicit rsBlockData splits the codewords into data / rsBlockData blocks.
  r.blocks = a.length > 6 ? r.data / +a[6] : 1;
  if (!Number.isInteger(r.blocks)) throw new Error(`blocks not integral: ${m[0]}`);
  rows.push(r);
}
if (rows.length !== 30) throw new Error(`expected 30 Data Matrix symbols, found ${rows.length}`);

writeFileSync('src/datamatrixdata.ts', `${header('Data Matrix ECC 200 symbol table')}
/** One Data Matrix ECC 200 symbol size: data and error-correction codeword
 *  counts, one data region's size in modules, the number of data regions and
 *  the number of interleaved Reed-Solomon blocks. */
export interface DmSymbol {
  readonly rect: boolean;
  readonly data: number;
  readonly ec: number;
  readonly regionW: number;
  readonly regionH: number;
  readonly regions: number;
  readonly blocks: number;
}

/** Every ECC 200 size, smallest data capacity first within the order ZXing lists. */
export const DM_SYMBOLS: readonly DmSymbol[] = [
${rows.map((r) => `  { rect: ${r.rect}, data: ${r.data}, ec: ${r.ec}, regionW: ${r.regionW}, regionH: ${r.regionH}, regions: ${r.regions}, blocks: ${r.blocks} },`).join('\n')}
];
`);

console.log('wrote src/pdf417data.ts, src/datamatrixdata.ts, test/fixtures/barcode-zxing/pdf417-ec.json');
