// One-time OFFLINE generator for JPEG 2000 test fixtures. NOT run in CI and NOT a
// runtime dependency of the library. It uses a WASM OpenJPEG build only to mint the
// base64 codestreams committed in test/helpers/jpx-fixtures.ts.
//
// Regenerate:
//   npm install --save-dev @cornerstonejs/codec-openjpeg
//   node scripts/gen-jpx-fixtures.mjs
//   npm uninstall @cornerstonejs/codec-openjpeg
//
// The encoder here emits single quality-layer streams only (its embind surface has
// no setNumLayers), so the multi-layer fixtures are produced by re-layering its
// output offline — see scripts/jpx-relayer.mjs — and every re-layered stream is
// verified by decoding it back through this same WASM OpenJPEG decoder before
// anything is written.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { relayer } from './jpx-relayer.mjs';
const require = createRequire(import.meta.url);
const Module = await require('@cornerstonejs/codec-openjpeg')();

const W = 16, H = 16;

/** Deterministic test rasters. */
function grayRamp() {
  const s = new Uint8Array(W * H);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) s[y * W + x] = ((x * 255) / (W - 1)) | 0;
  return s;
}
function rgbGradient() {
  const s = new Uint8Array(W * H * 3);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const i = (y * W + x) * 3;
    s[i] = ((x * 255) / (W - 1)) | 0;
    s[i + 1] = ((y * 255) / (H - 1)) | 0;
    s[i + 2] = (((x + y) * 255) / (W + H - 2)) | 0;
  }
  return s;
}

/** Encode raster → raw J2K codestream. */
function encode(src, comps, { reversible = true, progression = 0, ratio = 0, decompositions = 3 } = {}) {
  const e = new Module.J2KEncoder();
  const fi = { width: W, height: H, bitsPerSample: 8, componentCount: comps, isSigned: false };
  const d = e.getDecodedBuffer(fi);
  d.set(src);
  e.setQuality(reversible, 0);
  e.setDecompositions(decompositions);
  e.setProgressionOrder(progression);
  if (ratio) e.setCompressionRatio(ratio);
  e.encode();
  return e.getEncodedBuffer().slice();
}

/** Decode a raw J2K codestream → interleaved samples (ground truth). */
function decode(j2k) {
  const dec = new Module.J2KDecoder();
  const buf = dec.getEncodedBuffer(j2k.length);
  buf.set(j2k);
  dec.decode();
  return dec.getDecodedBuffer().slice();
}

/** Wrap a raw J2K codestream in a minimal JP2 box container. */
function jp2Wrap(j2k, comps) {
  const box = (type, payload) => {
    const b = new Uint8Array(8 + payload.length);
    const len = b.length;
    b[0] = (len >>> 24) & 0xff; b[1] = (len >>> 16) & 0xff; b[2] = (len >>> 8) & 0xff; b[3] = len & 0xff;
    for (let i = 0; i < 4; i++) b[4 + i] = type.charCodeAt(i);
    b.set(payload, 8);
    return b;
  };
  const sig = box('jP  ', Uint8Array.from([0x0d, 0x0a, 0x87, 0x0a]));
  const ftyp = box('ftyp', Uint8Array.from([0x6a, 0x70, 0x32, 0x20, 0, 0, 0, 0, 0x6a, 0x70, 0x32, 0x20])); // 'jp2 ', minor 0, compat 'jp2 '
  const ihdr = box('ihdr', Uint8Array.from([
    (H >>> 24) & 0xff, (H >>> 16) & 0xff, (H >>> 8) & 0xff, H & 0xff,
    (W >>> 24) & 0xff, (W >>> 16) & 0xff, (W >>> 8) & 0xff, W & 0xff,
    0, comps, 7, 7, 0, 0, // NC, BPC(=8→7), C(=7 wavelet), UnkC, IPR
  ]));
  const colr = box('colr', Uint8Array.from([1, 0, 0, 0, 0, 0, comps === 1 ? 17 : 16])); // METH=1, EnumCS 17 grey / 16 sRGB
  const jp2h = box('jp2h', concat(ihdr, colr));
  const jp2c = box('jp2c', j2k);
  return concat(sig, ftyp, jp2h, jp2c);
}
function concat(...arrs) {
  const total = arrs.reduce((a, x) => a + x.length, 0);
  const out = new Uint8Array(total);
  let o = 0; for (const a of arrs) { out.set(a, o); o += a.length; }
  return out;
}

const b64 = (u8) => Buffer.from(u8).toString('base64');
const out = [];
out.push('// GENERATED by scripts/gen-jpx-fixtures.mjs — do not edit by hand.');
out.push('// Regenerate: see the script header (needs a dev-only WASM OpenJPEG).');
out.push('/* eslint-disable */');
out.push('function b64(s: string): Uint8Array { return Uint8Array.from(Buffer.from(s, "base64")); }');
out.push('export interface JpxFixtureRgb { width: number; height: number; comps: number; data: Uint8Array }');

function emit(name, j2k, rgb, comps) {
  out.push(`export const ${name}_j2k: Uint8Array = b64(${JSON.stringify(b64(j2k))});`);
  out.push(`export const ${name}_rgb: JpxFixtureRgb = { width: ${W}, height: ${H}, comps: ${comps}, data: b64(${JSON.stringify(b64(rgb))}) };`);
}

/** Emit a codestream with no paired ground truth (it reuses another fixture's). */
function emitStreamOnly(name, j2k) {
  out.push(`export const ${name}_j2k: Uint8Array = b64(${JSON.stringify(b64(j2k))});`);
}

/** Validation gate: a re-layered stream must decode through the real OpenJPEG
 *  decoder to exactly the source samples. Our packet writer is otherwise checked
 *  only by our own packet reader, where a shared misreading of Annex B.10 would
 *  pass silently. Throws rather than writing a bad fixture. */
function assertOpenJpegDecodes(name, j2k, expected) {
  const got = decode(j2k);
  if (got.length !== expected.length) throw new Error(`${name}: OpenJPEG returned ${got.length} samples, expected ${expected.length}`);
  for (let i = 0; i < got.length; i++) {
    if (got[i] !== expected[i]) throw new Error(`${name}: OpenJPEG decode differs at sample ${i} (${got[i]} != ${expected[i]})`);
  }
  console.log(`  ${name}: OpenJPEG round-trip OK`);
}

const gray = grayRamp();
const rgb = rgbGradient();

// 1) 5/3 lossless grayscale, LRCP — exact (ground truth = source).
const glossless = encode(gray, 1, { reversible: true, progression: 0 });
emit('lossless_gray', glossless, gray, 1);

// 2) 9/7 lossy RGB — ground truth = a real decode of the stream.
const rlossy = encode(rgb, 3, { reversible: false, progression: 0, ratio: 20 });
emit('lossy_rgb', rlossy, decode(rlossy), 3);

// 3) RPCL progression order (5/3 lossless RGB) — exact.
const rrpcl = encode(rgb, 3, { reversible: true, progression: 2 });
emit('rpcl', rrpcl, rgb, 3);

// 4) JP2 box container (5/3 lossless grayscale) — exact.
emit('jp2box', jp2Wrap(glossless, 1), gray, 1);

// 5) Multi-layer (3 quality layers), 5/3 lossless grayscale, LRCP — exact.
//    Ground truth is fixture 1's, since re-layering is sample-preserving.
const gray3 = relayer(glossless, 3);
assertOpenJpegDecodes('multilayer_gray', gray3, gray);
emitStreamOnly('multilayer_gray', gray3);

// 6) Multi-layer (3 quality layers), 5/3 lossless RGB, LRCP — exact.
//    A fresh LRCP encode: fixture 3 is RPCL, and we want the layer loop nested
//    across components in progression order 0.
const rgbLrcp = encode(rgb, 3, { reversible: true, progression: 0 });
const rgb3 = relayer(rgbLrcp, 3);
assertOpenJpegDecodes('multilayer_rgb', rgb3, rgb);
emit('multilayer_rgb', rgb3, rgb, 3);

writeFileSync(new URL('../test/helpers/jpx-fixtures.ts', import.meta.url), out.join('\n') + '\n');
console.log('wrote test/helpers/jpx-fixtures.ts');
